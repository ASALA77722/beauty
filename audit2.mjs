import puppeteer from 'puppeteer-core'
import chromium from '@sparticuz/chromium'
const browser = await puppeteer.launch({ args: [...chromium.args], executablePath: await chromium.executablePath(), headless: 'shell' })
const page = await browser.newPage()
await page.setViewport({ width: 1440, height: 1000, deviceScaleFactor: 1 })
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle0', timeout: 60000 })
await page.evaluate(() => document.fonts.ready)
await new Promise(r => setTimeout(r, 900))
await page.screenshot({ path: 'apercu/v2-hero.png' })
await page.evaluate(() => document.querySelector('#boutique')?.scrollIntoView()); await new Promise(r => setTimeout(r, 700))
await page.screenshot({ path: 'apercu/v2-catalogue.png' })
await page.evaluate(() => document.querySelector('#offres')?.scrollIntoView()); await new Promise(r => setTimeout(r, 700))
await page.screenshot({ path: 'apercu/v2-offres.png' })
// mobile
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 })
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle0' })
await new Promise(r => setTimeout(r, 900))
await page.screenshot({ path: 'apercu/v2-mobile.png' })
const mob = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth > window.innerWidth, w: document.documentElement.scrollWidth }))
console.log('mobile', JSON.stringify(mob))
await browser.close()
